import assert from 'node:assert/strict';
import { build } from 'rolldown';
import { mkdir } from 'node:fs/promises';
await mkdir('.sites-runtime/demo-tests', { recursive: true });
await build({ input: 'demo/storage.ts', platform: 'node', output: { file: '.sites-runtime/demo-tests/storage.mjs', format: 'esm' } });
const storage = new Map();
globalThis.localStorage = { getItem: key => storage.get(key) ?? null, setItem: (key, value) => storage.set(key, value), removeItem: key => storage.delete(key) };
const { demoRequest } = await import('../.sites-runtime/demo-tests/storage.mjs');
const url = new URL('https://demo.example/api/study');
async function get() { return (await demoRequest(url)).json(); }
async function post(action, data = {}) { const response = await demoRequest(url, { method: 'POST', body: JSON.stringify({ action, ...data }) }); return { status: response.status, data: await response.json() }; }
const teacher = await get();
assert.equal(teacher.user.role, 'teacher');
assert.equal(teacher.lessons.length, 3);
const lesson = teacher.lessons.find(l => l.topic === 'Electricity');
localStorage.setItem('studyscan-demo-role', 'student');
assert.equal((await get()).lessons.length, 3);
assert.equal((await post('class', { name: 'Unauthorized' })).status, 400);
const question = await post('ask', { lesson: lesson.id, question: 'Explain Electricity in simpler terms.' });
assert.equal(question.data.status, 'reference');
assert.ok(question.data.sources.length > 0);
assert.match(question.data.answer, /Live AI is not connected/);
await post('flag', { id: question.data.id });
assert.equal((await get()).interactions[0].flagged, 1);
localStorage.setItem('studyscan-demo-role', 'teacher');
await post('review', { id: question.data.id, note: 'Let us review voltage together.', resolved: true });
await post('lesson', { lesson: { ...lesson, policy: { ...lesson.policy, enabled: false } } });
localStorage.setItem('studyscan-demo-role', 'student');
assert.equal((await get()).interactions[0].note, 'Let us review voltage together.');
assert.equal((await post('ask', { lesson: lesson.id, question: 'Explain voltage.' })).data.status, 'restricted');
assert.equal((await post('review', { id: question.data.id, note: 'Unauthorized' })).status, 400);
const motion = teacher.lessons[0];
assert.equal((await post('ask', { lesson: motion.id, question: 'Who won the election?' })).data.status, 'out-of-scope');
await post('progress', { lesson: motion.id, completed: true });
assert.equal((await get()).progress[0].completed, 1);
localStorage.setItem('studyscan-demo-role', 'teacher');
await post('deleteLesson', { id: lesson.id });
assert.equal((await get()).interactions.filter(i => i.lesson === lesson.id).length, 0);
localStorage.setItem('studyscan-demo-role', 'student');
assert.equal((await post('ask', { lesson: lesson.id, question: 'Explain voltage.' })).status, 400);
console.log('Demo flow verified: roles, sample lessons, source retrieval, flags, review notes, restrictions, progress, and deletion.');
assert.equal((await post('setRole',{id:'demo-student',role:'super-admin'})).status,400);
localStorage.setItem('studyscan-demo-role','super-admin');
const admin=await get();assert.equal(admin.user.role,'super-admin');assert.equal(admin.interactions.length,0);assert.equal(admin.lessons.length,0);assert.equal(admin.admin.accounts.length,4);
assert.equal((await post('setRole',{id:'demo-admin',role:'student'})).status,400);
assert.equal((await post('setRole',{id:'demo-new-account',role:'teacher'})).status,200);
assert.equal((await post('setAccountStatus',{id:'demo-student',status:'suspended'})).status,200);
localStorage.setItem('studyscan-demo-role','student');assert.equal((await demoRequest(url)).status,403);
localStorage.setItem('studyscan-demo-role','super-admin');await post('setAccountStatus',{id:'demo-student',status:'active'});
await post('schoolSettings',{name:'Demo School',aiEnabled:false,blockedTopics:''});
localStorage.setItem('studyscan-demo-role','student');assert.equal((await post('ask',{lesson:motion.id,question:'Explain force.'})).data.status,'restricted');assert.equal((await get()).admin,undefined);
localStorage.setItem('studyscan-demo-role','super-admin');assert.ok((await get()).admin.audit.length>=4);
console.log('Super Admin demo verified: protected owner, role updates, suspension, private summaries, school policy, and audit log.');
